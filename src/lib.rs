//! # Comparison with Existing Crates
//!
//! ## Definition
//!
//! | Feature | `bitflags-lite` | `bitflags` v2 | `enumflags2` v0.7 |
//! |:--:|:--:|:--:|:--:|
//! | Defined by trait impl | ✅ `BitFlagsSpec<T>` | ⛔️ No | ⛔️ No |
//! | Defined by macro | ✅ `bitflags!` | ✅ `bitflags!` | ⛔️ No |
//! | Defined by attribute | ⛔️ No | ⛔️ No | ✅ `#[bitflags(...)]` |
//! | Generates a distinct new type | ⛔️ No (generic over `U`) | ✅ Yes | ⛔️ No (uses user enum) |
//!
//! ## Type model
//!
//! | Feature | `bitflags-lite` | `bitflags` v2 | `enumflags2` v0.7 |
//! |:--:|:--:|:--:|:--:|
//! | Single-flag vs. set distinction | ✅ `BitFlag` / `BitFlags` | ⛔️ No | ✅ `T` / `BitFlags` |
//! | Iteration yields | `BitFlag<T, U>` | `Flags` (self, one bit) | `enum T` (variant) |
//! | Match exhaustively on single flag | ⛔️ No | ⛔️ No | ✅ `match flag { T::A => ... }` |
//! | Generic over a single flag | ✅ `BitFlag<T, U>` | ⛔️ No | ✅ `enum T` |
//! | Generic over flag sets | ✅ `BitFlags<T, U>` | ⛔️ No | ✅ `BitFlags<T, N>` |
//!
//! ## Extension
//!
//! | Feature | `bitflags-lite` | `bitflags` v2 | `enumflags2` v0.7 |
//! |:--:|:--:|:--:|:--:|
//! | Flag values as `Type::NAME` | ⛔️ No | ✅ Via const | ✅ Via variant |
//! | Inherent methods | ⛔️ No | ✅ Yes | ⛔️ No |
//! | Third-party trait impls | ⛔️ No | ✅ Yes | ⛔️ No |
//! | Local trait impls | ✅ Yes | ✅ Yes | ✅ Yes |
//!
//! ## Capabilities
//!
//! | Feature | `bitflags-lite` | `bitflags` v2 | `enumflags2` v0.7 |
//! |:--:|:--:|:--:|:--:|
//! | Most methods const | ✅ Integer impls | ✅ Targeted codegen | ⚠️ Limited |
//! | Multi-bit flags | ⚠️ Parse-only | ✅ Format and parse | ⛔️ No |
//! | Custom display name | ✅ Yes | ✅ `#[name]` | ⛔️ No |
//! | Alias names for parsing | ✅ Yes | ⛔️ No | ⛔️ No |
//! | Format with names | ✅ Yes | ✅ Yes | ✅ Yes |
//! | Parse from names | ✅ Yes | ✅ Yes | ⛔️ No |
//! | Case-insensitive parsing | ✅ Configurable | ⛔️ No | ⛔️ No |
//! | Custom default value | ✅ `#![default]` | ✅ `#[default]` | ✅ `#[default]` |
//! | Only valid bits representable | ⛔️ No | ⛔️ No | ✅ Yes |
//! | Invalid bits representable | ✅ Yes | ✅ Yes | ⛔️ No |
//!
//! <!---
//!   Invalid bits are really not allowed in `enumflags2`.
//!   Its `from_bits_unchecked` unsafe method requires that
//!   "All bits set in val must correspond to a value of the enum".
//! -->
